// ═══════════════════════════════════════════════════════════════════════════════

pub fn generatePython(allocator: Allocator, spec: ParsedSpec) ![]u8 {
    _ = allocator;
    var result: std.ArrayListUnmanaged(u8) = .empty;

    try result.print(allocator, "# {s} v{s}\n", .{ spec.name, spec.version });
    try result.print(allocator, "# Generated by VIBEE Multi-Language Generator\n", .{});
    try result.print(allocator, "# φ² + 1/φ² = 3\n\n", .{});
    try result.print(allocator, "from dataclasses import dataclass\n", .{});
    try result.print(allocator, "from typing import Optional, List, Dict, Any\n\n", .{});

    for (spec.types) |t| {
        try result.print(allocator, "@dataclass\n", .{});
        try result.print(allocator, "class {s}:\n", .{t.name});
        if (t.fields.len == 0) {
            try result.print(allocator, "    pass\n\n", .{});
        } else {
            for (t.fields) |f| {
                const py_type = mapTypePython(f.type_name);
                try result.print(allocator, "    {s}: {s}\n", .{ f.name, py_type });
            }
            try result.print(allocator, "\n", .{});
        }
    }

    for (spec.behaviors) |b| {
        try result.print(allocator, "def {s}():\n", .{b.name});
        try result.print(allocator, "    \"\"\"Given: {s}, When: {s}, Then: {s}\"\"\"\n", .{ b.given, b.when, b.then });
        try result.print(allocator, "    pass\n\n", .{});
    }

    return result.toOwnedSlice(allocator);
}

