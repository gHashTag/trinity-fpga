// ═══════════════════════════════════════════════════════════════════════════════
// SQL GENERATOR
// ═══════════════════════════════════════════════════════════════════════════════

pub fn generateSQL(allocator: Allocator, spec: ParsedSpec) ![]u8 {
    _ = allocator;
    var result: std.ArrayListUnmanaged(u8) = .empty;

    try result.print(allocator, "-- {s} v{s}\n", .{ spec.name, spec.version });
    try result.print(allocator, "-- Generated by VIBEE Multi-Language Generator\n", .{});
    try result.print(allocator, "-- φ² + 1/φ² = 3\n\n", .{});

    // Generate CREATE TABLE statements for each type
    for (spec.types) |t| {
        try result.print(allocator, "CREATE TABLE IF NOT EXISTS {s} (\n", .{t.name});
        try result.print(allocator, "    id SERIAL PRIMARY KEY", .{});

        for (t.fields) |f| {
            const sql_type = mapTypeSQL(f.type_name);
            try result.print(allocator, ",\n    {s} {s}", .{ f.name, sql_type });
        }

        try result.print(allocator, ",\n    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP", .{});
        try result.print(allocator, ",\n    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP\n", .{});
        try result.print(allocator, ");\n\n", .{});
    }

    // Generate stored procedures for behaviors
    for (spec.behaviors) |b| {
        try result.print(allocator, "-- Behavior: {s}\n", .{b.name});
        try result.print(allocator, "-- Given: {s}\n", .{b.given});
        try result.print(allocator, "-- When: {s}\n", .{b.when});
        try result.print(allocator, "-- Then: {s}\n", .{b.then});
        try result.print(allocator, "CREATE OR REPLACE FUNCTION {s}()\n", .{b.name});
        try result.print(allocator, "RETURNS VOID AS $$\n", .{});
        try result.print(allocator, "BEGIN\n", .{});
        try result.print(allocator, "    -- TODO: implement\n", .{});
        try result.print(allocator, "    NULL;\n", .{});
        try result.print(allocator, "END;\n", .{});
        try result.print(allocator, "$$ LANGUAGE plpgsql;\n\n", .{});
    }

    return result.toOwnedSlice(allocator);
}

