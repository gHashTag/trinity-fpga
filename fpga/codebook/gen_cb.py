#!/usr/bin/env python3
"""Emit the arbitrary-codebook decoder at a given fractional width.

The KL-optimised codebook's levels are not dyadic, so unlike E2M1 they cannot be
carried exactly in any finite fixed-point field. The table is therefore a
function of a chosen width B, and the RTL is generated from the levels rather
than hand-typed, so the constants in the netlist and the constants the
perplexity run used are the same objects.

Convention: level i -> round(L_i * 2^B), an unsigned (B+1)-bit integer whose top
entry is exactly 2^B. The implied constant 2^-B is a power of two and folds into
the shared E8M0 exponent for free -- the same free fold E2M1 gets for its 0.5,
so neither format is charged for its normalisation.
"""
import os, sys

KL = [0.0, 0.07701, 0.18828, 0.31396, 0.46561, 0.6113, 0.79074, 1.0]
HERE = os.path.dirname(os.path.abspath(__file__))

def table(B):
    ints = [round(x * (1 << B)) for x in KL]
    assert all(ints[i] < ints[i + 1] for i in range(7)), f"not monotone at B={B}: {ints}"
    assert len(set(ints)) == 8, f"not distinct at B={B}: {ints}"
    return ints

def emit(B):
    t = table(B)
    MW = B + 1                      # unsigned magnitude width, top level = 2^B
    lines = []
    lines.append("// Arbitrary 8-entry codebook decode -- the challenger.")
    lines.append("//")
    lines.append("// GENERATED by gen_cb.py; do not edit. Levels, exact:")
    lines.append("//   " + ", ".join(f"{x:.5f}" for x in KL))
    lines.append(f"// quantised to {B} fractional bits (round-to-nearest):")
    lines.append("//   " + ", ".join(f"{v}/{1<<B} = {v/(1<<B):.5f}" for v in t))
    lines.append("// monotone: yes.  distinct: yes.  both asserted at generation time.")
    lines.append("//")
    lines.append("// There is no arithmetic here and there cannot be: the levels are not")
    lines.append("// dyadic, so no shift-and-add of the code reproduces them. This is the")
    lines.append("// lookup whose cost is the question.")
    lines.append("`default_nettype none")
    lines.append(f"module cb4_decode_b{B} (")
    lines.append("    input  wire        [3:0] code,   // {sign, index[2:0]}")
    lines.append(f"    output wire signed [{MW}:0] w       // two's complement, units of 2^-{B}")
    lines.append(");")
    lines.append("    wire       s = code[3];")
    lines.append("    wire [2:0] i = code[2:0];")
    lines.append(f"    reg  [{MW-1}:0] mag;")
    lines.append("    always @(*) case (i)")
    for k, v in enumerate(t):
        lines.append(f"      3'd{k}: mag = {MW}'d{v};")
    lines.append("    endcase")
    lines.append("    assign w = s ? -$signed({1'b0, mag}) : $signed({1'b0, mag});")
    lines.append("endmodule")
    lines.append("`default_nettype wire")
    p = os.path.join(HERE, f"cb4_decode_b{B}.v")
    open(p, "w").write("\n".join(lines) + "\n")
    return p, MW, t

if __name__ == "__main__":
    for B in [int(a) for a in sys.argv[1:]] or [4, 5, 6, 8, 10]:
        p, MW, t = emit(B)
        print(f"B={B:2d}  mag width {MW}  signed width {MW+1}  table {t}  -> {os.path.basename(p)}")
