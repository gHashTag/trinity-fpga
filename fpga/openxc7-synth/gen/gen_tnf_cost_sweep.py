#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_tnf_cost_sweep.py — generate the (E_t, M) wrapper tops for the TNF cost sweep.

Why this is possible without new RTL
------------------------------------
A TNF exponent field is a *binary* field of b = ceil(E_t log2 3) cells holding a
balanced-ternary-derived offset.  The adder datapath never sees a trit: it aligns
two offsets, adds or subtracts mantissas, normalises and rounds.  That is exactly
what gf_adder_param already does, at EXP_BITS = b and MANT_BITS = M.  The ternary
character of TNF lives in the encoding and in the value set, not in the datapath,
so the cost sweep reuses the audited parameterised core rather than introducing a
second, unaudited one.  This also means the sweep measures the cost of the FIELD
LAYOUT, which is precisely what the phi rule chooses, and nothing else.

What the sweep is for
---------------------
The published cost model
    LUT ~ 2.194 M^2 + 53.84 M - 197.1 E_t + 363.5,  R^2 = 0.9989
is fitted on post-route rows with M <= 25 only, and the two TNF16 rows at M = 9
and M = 11 are mutually inconsistent with any smooth model.  Two questions the
sweep is designed to answer, and it may well answer them against us:

  Q1  Do the two TNF16 rows stay inconsistent when both are re-measured through
      one identical flow?  If they reconcile, the earlier inconsistency was a
      flow artefact and must be reported as such.
  Q2  Does the M^2 term survive past M = 25, or does growth flatten?  The two
      widest previously measured rungs grow far more slowly than M^2, which is
      the reason the model is not extrapolated.  If growth flattens, the
      quadratic is a local fit and must be labelled as one.

Nothing here is a hardware claim.  yosys stat is [modelled]; nextpnr post-route
is [measured CI-synth]; only a UART transcript from the AX7203 with a CI URL, an
artefact SHA256 and IDCODE 0x13636093 is [measured on hardware].
"""
import json
import math
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tnf_cost")
BUDGET = 40                    # physical cells; keeps every arm routable on XC7A200T


def exp_bits(et):
    return math.ceil(et * math.log2(3))


def grid():
    """(E_t, M) points chosen to answer Q1 and Q2, not to fill a rectangle."""
    pts = []
    for et in (2, 3, 4, 5, 6):
        b = exp_bits(et)
        for m in (1, 4, 8, 9, 11, 13, 17, 21, 25, 29, 33):
            phys = 1 + b + m
            if phys > BUDGET:
                continue
            pts.append(dict(et=et, exp_bits=b, m=m, phys=phys,
                            nominal=1 + et + m,
                            binades=(3 ** et - 1) // 2))
    return pts


TOP = """// {name}.v -- GENERATED by gen/gen_tnf_cost_sweep.py, do not edit by hand.
// TNF cost-sweep arm: E_t = {et} trits of balanced exponent -> {b} binary cells,
// M = {m} mantissa bits.  Physical width {phys} cells; nominal width {nominal}
// under the specification convention 1 + E_t + M.  Exponent reach +-{binades}
// binades.  The two widths differ and the difference is the point: any accuracy
// claim must name which convention it uses.
//
// HAS_INF = 1: TNF reserves the top offset row for the non-finite class, so
// exp = all-ones must not decode as a finite maximum.
module {name}(
    input clk, input rst,
    input in_valid, input [{hi}:0] in_a, input [{hi}:0] in_b,
    output in_ready, output out_valid, output [{hi}:0] out_y, input out_ready
);
    {core} #(.EXP_BITS({b}), .MANT_BITS({m}), .HAS_INF(1){extra}) u (
        .clk(clk), .rst(rst), .in_valid(in_valid), .in_a(in_a), .in_b(in_b),
        .in_ready(in_ready), .out_valid(out_valid), .out_y(out_y), .out_ready(out_ready)
    );
endmodule
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    pts = grid()
    arms = []
    for p in pts:
        w = 1 + p["exp_bits"] + p["m"]
        for op, core in (("add", "gf_adder_param"), ("mul", "gf_mul_param")):
            name = f"tnf_cost_e{p['et']}m{p['m']}_{op}_top"
            # wide mantissas need the 2-stage split; the threshold is the same
            # one gf_adder_param documents for GF64
            extra = ", .PIPELINE(1)" if p["m"] >= 25 else ""
            src = TOP.format(name=name, et=p["et"], b=p["exp_bits"], m=p["m"],
                             phys=p["phys"], nominal=p["nominal"],
                             binades=p["binades"], hi=w - 1, core=core,
                             extra=extra if core == "gf_adder_param" else "")
            with open(os.path.join(OUT, name + ".v"), "w") as fh:
                fh.write(src)
            arms.append(dict(top=name, op=op, core=core, width=w, **p))
    man = os.path.join(OUT, "manifest.json")
    with open(man, "w") as fh:
        json.dump(dict(budget_cells=BUDGET, arms=arms,
                       note="yosys stat = [modelled]; nextpnr post-route = "
                            "[measured CI-synth]; hardware requires UART + SHA256 "
                            "+ IDCODE 0x13636093 on issue #199"),
                  fh, indent=1)
    print(f"{len(arms)} arms over {len(pts)} (E_t, M) points -> {OUT}")
    print(f"{'E_t':>4}{'b':>4}{'M':>5}{'phys':>6}{'nominal':>8}{'binades':>9}")
    for p in pts:
        print(f"{p['et']:>4}{p['exp_bits']:>4}{p['m']:>5}{p['phys']:>6}"
              f"{p['nominal']:>8}{p['binades']:>9}")
    print(f"manifest -> {man}")


if __name__ == "__main__":
    sys.exit(main())
