def golden_takum8(code):
    code &= 0xFF
    return T27_VECTORS.get(code, 0x00000000)


def hw_exchange(ser, code):
    import serial
    pkt = FRAME + bytes([FMT_TAKUM8 & 0xFF, code & 0xFF, 0x00, 0x00])
    ser.write(pkt)
    resp = ser.read(5)
    if len(resp) != 5 or resp[0] != 0xA5:
        return None
    return struct.unpack("<I", resp[1:5])[0]


def self_test():
    bad = 0
    for code, exp in list(T27_VECTORS.items())[:8]:
        if golden_takum8(code) != exp:
            bad += 1
    print(f"self-test: golden lookup first 8 of {len(T27_VECTORS)} vectors, {bad} failures")
    return bad == 0


def run_hw(port, baud):
    import serial
    import serial
    ser = serial.Serial(port, baud, timeout=2)
    fails = 0; checked = 0
    for code in range(256):
        hw = hw_exchange(ser, code)
        gold = golden_takum8(code)
        checked += 1
        if hw is None or hw != gold:
            fails += 1
            if fails <= 10:
                print(f"MISMATCH code=0x{code:02x} hw=0x{hw if hw is not None else 0:08x} gold=0x{gold:08x}")
    ser.close()
    print(f"HW RESULT: {checked - fails}/{checked} bit-exact (fails={fails})")
    return fails == 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--port", default="/dev/cu.usbserial-1120")
    ap.add_argument("--baud", type=int, default=160000)
    a = ap.parse_args()
    if a.self_test:
        sys.exit(0 if self_test() else 1)
    sys.exit(0 if run_hw(a.port, a.baud) else 1)


if __name__ == "__main__":
    main()
